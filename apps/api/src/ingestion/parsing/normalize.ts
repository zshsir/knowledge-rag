/**
 * 入库前的文本归一化：把「各种来源的脏文本」收敛成同一种形状，让下游只看一套规则。
 *
 * 为什么它是公共前提而不是某个解析器的私事（调用方一共四处文件、五处调用）：
 * - text.parser.ts:64：TXT/MD 解码后（UTF-8 支与 GB18030 回退支都走这里，两支产出形状必须一致）
 * - parser.service.ts:77：所有格式的统一兜底判空
 * - parser.service.ts:140：PDF 的「归一化后短于 20 字符视为扫描件」——这个长度闸口直接依赖归一化结果，
 *   空行少折叠一步，空白页拼起来的字符串就可能刚好过线
 * - parser.service.ts:162：DOCX 的判空
 * - chunker.ts:38：切分之前再归一化一次
 * 也就是说三条提取路径各自归一化、切分器又归一化一次。这不是笔误：
 * 归一化是【稳定】的（同一份文本做两次结果相同），所以多跑一次只是冗余；
 * 反过来若哪天把它从 parser 层摘掉，判空与长度闸口就会按未清洗的文本算，行为立刻漂。
 *
 * 刻意不做的事（边界，别指望这里）：
 * - 不做编码探测：那是 text.parser.ts 的 GB18030 回退，本函数只接字符串
 * - 不压缩行中间的连续空格/制表符：正文里的排版空白要原样保留，否则会改动展示与引用内容
 * - 不去 BOM：UTF-8 的前导 BOM 在 TextDecoder 那一层就已经被吃掉了（text.parser.ts 步骤 1）
 * - 不截断长度：片段上限由切分器按 CHUNK_SIZE 负责，配置配错也不是这里拦
 *   （config.service.ts 的 assertChunkingConfig 才是那道闸）
 * - 不抛异常：空文本一律返回空串，「空就是 400」的判断留给调用方，因为 PDF 那边还多一条长度闸
 */

/**
 * 四步 replace + 一次 trim；这四步的顺序是有依赖关系的，别单独调整某一行。
 * 步骤：
 * 1. 行尾统一成 '\n'：`\r\n?` 同时吃掉 CRLF（Windows 记事本）与孤立的 CR（老 Mac 文本）。
 *    不做这一步，后面所有按 '\n' 写的正则和切分器的分隔符优先级都会错位
 * 2. 删掉 NUL（U+0000）：老 TXT 与部分 PDF 提取里会混进它。留着有害——
 *    Postgres 的 text 值不允许 NUL 字符，写 chunks 那一步会失败；即使不写库，
 *    它也照样占长度、也会在嵌入文本里留一个不可见字符
 * 3. 去掉「紧跟换行的空格与制表符」（行尾空白，不动行中间）。这一步必须排在第 4 步之前：
 *    像 '\n \n' 这种「空行里夹着空格」的段落分隔（PDF 逐页提取再拼接时很常见），
 *    先在这里收成 '\n\n'，第 4 步才折叠得动，切分器的首选分隔符 '\n\n'（chunker.ts:15）也才命中得到
 * 4. 三个及以上连续换行压成两个：段落边界只留一层，避免长空白把片段撑到超过 CHUNK_SIZE
 * 5. trim：去首尾空白。这一句同时是「只有空白 / 只有 BOM / 只有 NUL 的文件归一化后变空串」的实现点，
 *    text.parser.ts 与 parser.service.ts 的判空、以及 PDF 的长度闸口，靠的都是它返回 ''
 * 返回：清洗后的文本。输入为空串时返回空串（没有特殊分支，也不抛错）
 */
export function normalizeText(input: string): string {
  return input
    // 步骤 1：CRLF / 孤立 CR → LF
    .replace(/\r\n?/g, '\n')
    // 步骤 2：删 NUL
    .replace(/\u0000/g, '')
    // 步骤 3：清行尾水平空白（排在折叠空行之前，见上）
    .replace(/[ \t]+\n/g, '\n')
    // 步骤 4：折叠三个及以上的换行
    .replace(/\n{3,}/g, '\n\n')
    // 步骤 5：首尾空白
    .trim();
}
